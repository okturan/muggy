/**
 * Heat load: WBGT for a person in the shade and in the sun.
 *
 * The index is the one Japan's Ministry of the Environment publishes, because
 * Muggy's levels and alert marks are MOE's:
 *
 *   WBGT = 0.7 Tw + 0.2 Tg + 0.1 Ta
 *
 * Tw is MOE's psychrometric wet bulb (psychro.js). Tg is a 150 mm black globe:
 * Liljegren's energy balance with ISO 7726 globe convection (globe.js), fed
 * with what the forecast actually provides:
 *
 * - Direct fraction from the forecast's own direct/shortwave split; the model's
 *   estimate only when direct radiation is missing.
 * - Radiation is an average over the interval ending at its timestamp, so the
 *   sun is averaged over the sunlit part of that interval (sun.js) and the
 *   dark part counts as shade.
 * - Shade and sun share one 2 m wind, estimated from the site's actual
 *   irradiance with town exponents, and never below the calibrated minimum.
 *   The night gradient is not forecast; a stable night is assumed, which errs
 *   toward caution.
 * - Surface albedo and the minimum 2 m wind come from calibration.js, which is
 *   generated by the validation against measured WBGT.
 */
import { calcSolarParameters, estWindSpeed, stabSrdt, CZA_MIN } from './wbgt.js';
import { globeTemperature } from './globe.js';
import { wetBulbMoe } from './psychro.js';
import { sunOverInterval, czaAt } from './sun.js';
import { CALIBRATION } from './calibration.js';

export const ASSUMED_WIND_MS = 1.5;
const WIND_HEIGHT_M = 10;
const URBAN = 1;
const NIGHT_DT = 1;
// Below the model's horizon threshold, so no beam term, but never exactly 0
// (the globe equation divides by it).
const NIGHT_CZA = 0.004;

/** Whether the sun is up at this instant (for day/night wording; the load itself averages over its interval). */
export const isSunUp = (ms, lat, lon) => czaAt(ms, lat, lon) >= CZA_MIN;

/** Standard-atmosphere station pressure, hPa. */
export const pressureFromElevation = (m) => 1013.25 * (1 - 2.25577e-5 * (m || 0)) ** 5.25588;

/** Relative humidity (%) from temperature and dew point (Magnus, Alduchov-Eskridge). */
export function rhFromDewPoint(t, td) {
  const a = 17.625;
  const b = 243.04;
  return 100 * Math.exp((a * td) / (b + td) - (a * t) / (b + t));
}

function utcDay(ms) {
  const d = new Date(ms);
  return {
    year: d.getUTCFullYear(),
    month: d.getUTCMonth() + 1,
    day: d.getUTCDate() + (d.getUTCHours() + d.getUTCMinutes() / 60 + d.getUTCSeconds() / 3600) / 24,
  };
}

/**
 * MOE-definition WBGT for the interval (endMs - minutes, endMs].
 * i: { endMs, minutes, lat, lon, tair (°C), rh (%), wind10 (m/s), pres (hPa),
 *      sw, direct (W/m², interval means; sw null = unknown) }
 */
export function wbgtInterval(i, cfg = CALIBRATION) {
  const { endMs, minutes = 0, lat, lon, tair, rh, wind10, pres, sw, direct } = i;
  // sunOverride { fSun, cza } lets the About page explorer set the sun's height directly.
  const sun = i.sunOverride || sunOverInterval(endMs, minutes, lat, lon);
  const sunUp = sun.fSun > 0;
  const cza = sunUp ? sun.cza : NIGHT_CZA;
  const swLit = sunUp && sw != null && sw > 0 ? sw / sun.fSun : 0;
  const fdirData = direct != null && sw != null && sw > 0 ? Math.max(0, Math.min(0.9, direct / sw)) : undefined;

  const mid = utcDay(endMs - (minutes * 60000) / 2);
  const sp = calcSolarParameters(mid.year, mid.month, mid.day, lat, lon, swLit, fdirData, cza);
  if (!sp) return null;

  const stability = stabSrdt(sunUp, wind10, sp.solar, NIGHT_DT);
  const wind2 = Math.max(estWindSpeed(wind10, WIND_HEIGHT_M, stability, URBAN), cfg.minWind2);

  const tk = tair + 273.15;
  const rhf = rh / 100;
  const tw = wetBulbMoe(tair, rh, pres);
  const tgShade = globeTemperature(tk, rhf, wind2, 0, 0, cza, cfg.globeDiameter, cfg.surfaceAlbedo);
  if (tgShade == null) return null;
  const shade = 0.7 * tw + 0.2 * tgShade + 0.1 * tair;

  let sunValue = shade;
  let tgSun = tgShade;
  let sunKnown = true;
  if (sunUp) {
    if (sw == null) {
      sunKnown = false;
    } else if (sp.solar > 0) {
      const tgLit = globeTemperature(tk, rhf, wind2, sp.solar, sp.fdir, cza, cfg.globeDiameter, cfg.surfaceAlbedo);
      if (tgLit == null) {
        sunKnown = false;
      } else {
        tgSun = sun.fSun * tgLit + (1 - sun.fSun) * tgShade;
        sunValue = Math.max(shade, 0.7 * tw + 0.2 * tgSun + 0.1 * tair);
      }
    }
  }

  return { shade, sun: sunValue, sunUp, sunKnown, fSun: sun.fSun, cza: sunUp ? sun.cza : null, tw, tgShade, tgSun, wind2 };
}

/**
 * A forecast reading → the engine's interval inputs.
 *
 * r: { time (local ISO minute, end of the averaging interval), utcOffsetSeconds,
 *      avgMinutes, lat, lon, elevation, temperature_2m, relative_humidity_2m |
 *      dew_point_2m, wind_speed_10m (km/h), surface_pressure (hPa),
 *      shortwave_radiation, direct_radiation (W/m²) }
 *
 * Returns null when temperature or humidity is missing.
 */
export function intervalInputs(r) {
  const t = r.temperature_2m;
  let rh = r.relative_humidity_2m;
  if (rh == null && t != null && r.dew_point_2m != null) rh = Math.min(100, rhFromDewPoint(t, r.dew_point_2m));
  if (t == null || rh == null || !r.time) return null;
  const windKnown = r.wind_speed_10m != null;
  return {
    endMs: Date.parse(`${r.time}:00Z`) - (r.utcOffsetSeconds || 0) * 1000,
    minutes: r.avgMinutes || 0,
    lat: r.lat,
    lon: r.lon,
    tair: t,
    rh,
    wind10: windKnown ? r.wind_speed_10m / 3.6 : ASSUMED_WIND_MS,
    windKnown,
    pres: r.surface_pressure != null ? r.surface_pressure : pressureFromElevation(r.elevation),
    sw: r.shortwave_radiation,
    direct: r.direct_radiation,
  };
}

const memo = new Map();
const MEMO_MAX = 4000;

/**
 * Shade and sun WBGT for one forecast reading (see intervalInputs).
 * Returns null when temperature or humidity is missing, otherwise the
 * wbgtInterval result plus windKnown. sunKnown is false only in daylight
 * without radiation data; the sun value then equals shade and must not be
 * spoken about.
 */
export function loadAt(r, cfg = CALIBRATION) {
  const i = intervalInputs(r);
  if (!i) return null;
  const key = [i.endMs, i.minutes, i.lat, i.lon, i.tair.toFixed(2), i.rh.toFixed(1), i.wind10.toFixed(2), i.windKnown ? 1 : 0, i.pres.toFixed(1),
    i.sw == null ? '' : i.sw.toFixed(1), i.direct == null ? '' : i.direct.toFixed(1),
    cfg.globeDiameter, cfg.surfaceAlbedo, cfg.minWind2].join('|');
  const hit = memo.get(key);
  if (hit) return hit;
  const res = wbgtInterval(i, cfg);
  const out = res && { ...res, windKnown: i.windKnown };
  if (memo.size >= MEMO_MAX) memo.clear();
  memo.set(key, out);
  return out;
}

const placeOf = (data) => ({
  lat: data.latitude, lon: data.longitude, elevation: data.elevation, utcOffsetSeconds: data.utc_offset_seconds || 0,
});

/**
 * The reading for the current minute. Temperature, humidity, wind and pressure
 * come from the interpolated reading; radiation comes from the 15-minute step
 * whose averaging interval contains now, with the sun averaged over it.
 */
export function readingNow(data, cur) {
  const m = data.minutely_15;
  const reading = { ...placeOf(data), ...cur };
  if (m && m.time && m.time.length) {
    const j = m.time.findIndex((t) => t >= cur.time);
    if (j >= 0) {
      return {
        ...reading,
        time: m.time[j],
        avgMinutes: 15,
        shortwave_radiation: m.shortwave_radiation ? m.shortwave_radiation[j] : cur.shortwave_radiation,
        direct_radiation: m.direct_radiation ? m.direct_radiation[j] : cur.direct_radiation,
      };
    }
  }
  return { ...reading, avgMinutes: 0 };
}

/** Load for the current minute. */
export const loadNow = (data, cur, cfg = CALIBRATION) => loadAt(readingNow(data, cur), cfg);

/** Load for every forecast hour; hourly radiation covers the preceding hour. */
export function loadSeries(data, cfg = CALIBRATION) {
  const h = data.hourly;
  const place = placeOf(data);
  // utc_offset_seconds is fixed per response; a DST change inside the 7-day
  // window shifts later hours by one, a known and accepted limit.
  return h.time.map((time, i) => loadAt({
    ...place,
    time,
    avgMinutes: 60,
    temperature_2m: h.temperature_2m[i],
    relative_humidity_2m: h.relative_humidity_2m && h.relative_humidity_2m[i],
    dew_point_2m: h.dew_point_2m && h.dew_point_2m[i],
    wind_speed_10m: h.wind_speed_10m && h.wind_speed_10m[i],
    surface_pressure: h.surface_pressure && h.surface_pressure[i],
    shortwave_radiation: h.shortwave_radiation && h.shortwave_radiation[i],
    direct_radiation: h.direct_radiation && h.direct_radiation[i],
  }, cfg));
}
